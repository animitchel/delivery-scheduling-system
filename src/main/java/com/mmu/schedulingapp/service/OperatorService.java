package com.mmu.schedulingapp.service;

import com.mmu.schedulingapp.dto.operator.*;
import com.mmu.schedulingapp.mapper.OperatorMapper;
import com.mmu.schedulingapp.model.*;
import com.mmu.schedulingapp.repository.*;
import jakarta.persistence.*;
import jakarta.validation.Validator;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.transaction.annotation.Isolation;
import org.springframework.stereotype.Service;
import org.springframework.http.HttpStatus;
import org.springframework.web.server.ResponseStatusException;
import org.springframework.data.domain.*;
import java.util.*;

@Service
public class OperatorService {
    private final OperatorRepository operators;
    private final WarehouseRepository warehouses;
    private final EntityManager entities;
    private final Validator validator;
    @org.springframework.beans.factory.annotation.Autowired
    public OperatorService(OperatorRepository operators,WarehouseRepository warehouses,EntityManager entities,Validator validator) { this.operators=operators;this.warehouses=warehouses;this.entities=entities;this.validator=validator; }
    // Recording-service tests only use collection reads or overridden write methods.
    public OperatorService(OperatorRepository operators,WarehouseRepository warehouses) { this(operators,warehouses,null,null); }
    @Transactional(readOnly=true)
    public List<OperatorResponseDTO> getAllDriverDTOs() { return operators.findAll().stream().map(OperatorMapper::toResponseDTO).toList(); }
    @Transactional(readOnly=true)
    public Optional<OperatorResponseDTO> getDriver(int id) { return operators.findById(id).map(OperatorMapper::toResponseDTO); }
    @Transactional(readOnly=true)
    public Optional<OperatorState> snapshot(int id) { validId(id);return operators.findById(id).map(OperatorState::from); }
    @Transactional(readOnly=true,isolation=Isolation.REPEATABLE_READ)
    public OperatorDirectory directory(int page,int size,String search) {
        if(page<0||page>10000||size<1||size>50||search==null||search.length()>100) throw invalid("Invalid operator directory query.");
        String pattern="%"+search.strip().toLowerCase(Locale.ROOT).replace("!","!!").replace("%","!%").replace("_","!_")+"%";
        var result=operators.directory(pattern,PageRequest.of(page,size,Sort.by("name","operatorId")));
        return new OperatorDirectory(result.getContent(),page,size,result.getTotalElements(),result.getTotalPages());
    }
    @Transactional(isolation=Isolation.READ_COMMITTED)
    public OperatorState create(OperatorWriteRequest request) { return OperatorState.from(create(OperatorInput.from(request,validator))); }
    @Transactional(isolation=Isolation.READ_COMMITTED)
    public OperatorResponseDTO createDriver(OperatorRequestDTO request) {
        if(request.getOperatorId()!=null) throw invalid("Operator IDs are generated by the server.");
        var input=OperatorInput.from(request,legacyWarehouse(request.getWarehouseName()),validator);
        return OperatorMapper.toResponseDTO(create(input));
    }
    private Operator create(OperatorInput input) {
        if(input.status()==Operator.AvailabilityStatus.ON_DELIVERY) throw conflict("On-delivery availability is managed by route assignment.");
        var warehouse=warehouse(input.warehouseId());var operator=new Operator();input.apply(operator,warehouse);return operators.saveAndFlush(operator);
    }
    @Transactional(isolation=Isolation.READ_COMMITTED)
    public Optional<OperatorState> replace(int id,OperatorWriteRequest request,String etag) {
        validId(id);requireEtag(etag);var input=OperatorInput.from(request,validator);
        return locked(id).map(operator->{match(operator,etag);apply(operator,input);return OperatorState.from(operators.saveAndFlush(operator));});
    }
    @Transactional(isolation=Isolation.READ_COMMITTED)
    public Optional<OperatorResponseDTO> updateDriver(int id,OperatorRequestDTO request) {
        if(request.getOperatorId()!=null&&!request.getOperatorId().equals(id)) throw invalid("Operator ID does not match the requested record.");
        var input=OperatorInput.from(request,legacyWarehouse(request.getWarehouseName()),validator);
        return locked(id).map(operator->{apply(operator,input);return OperatorMapper.toResponseDTO(operators.saveAndFlush(operator));});
    }
    @Transactional(isolation=Isolation.READ_COMMITTED)
    public Optional<OperatorResponseDTO> patchDriver(int id,OperatorRequestDTO patch) {
        if(patch.getOperatorId()!=null&&!patch.getOperatorId().equals(id)) throw invalid("Operator ID does not match the requested record.");
        return locked(id).map(operator->{
            var merged=new OperatorRequestDTO();merged.setName(patch.getName()==null?operator.getName():patch.getName());merged.setPhoneNumber(patch.getPhoneNumber()==null?operator.getPhoneNumber():patch.getPhoneNumber());merged.setEmail(patch.getEmail()==null?operator.getEmail():patch.getEmail());
            merged.setVehicleType(patch.getVehicleType()==null?operator.getVehicleType():patch.getVehicleType());merged.setMaxCapacity(patch.getMaxCapacity()==null?operator.getMaxCapacity():patch.getMaxCapacity());merged.setAvailabilityStatus(patch.getAvailabilityStatus()==null?operator.getAvailabilityStatus():patch.getAvailabilityStatus());
            Integer warehouseId=patch.getWarehouseName()==null?(operator.getWarehouse()==null?null:operator.getWarehouse().getWarehouseId()):legacyWarehouse(patch.getWarehouseName());
            apply(operator,OperatorInput.from(merged,warehouseId,validator));return OperatorMapper.toResponseDTO(operators.saveAndFlush(operator));
        });
    }
    private void apply(Operator operator,OperatorInput input) {
        boolean assigned=operators.hasActiveRoutes(operator.getOperatorId())||operators.hasUnfinishedDeliveries(operator.getOperatorId());
        boolean operational=operator.getAvailabilityStatus()!=input.status() || !Objects.equals(operator.getWarehouse()==null?null:operator.getWarehouse().getWarehouseId(),input.warehouseId()) || !Objects.equals(operator.getVehicleType(),input.vehicleType()) || !Objects.equals(operator.getMaxCapacity(),input.maxCapacity());
        if(assigned&&operational) throw conflict("Finish assigned work before changing availability, warehouse, vehicle or capacity.");
        if(input.status()==Operator.AvailabilityStatus.ON_DELIVERY&&operator.getAvailabilityStatus()!=input.status()) throw conflict("On-delivery availability is managed by route assignment.");
        if(operator.getAvailabilityStatus()==Operator.AvailabilityStatus.ON_DELIVERY&&input.status()!=operator.getAvailabilityStatus()) throw conflict("On-delivery availability must be reconciled through the route lifecycle.");
        input.apply(operator,warehouse(input.warehouseId()));
    }
    private Warehouse warehouse(int id) {
        var warehouse=warehouses.lockById(id).orElseThrow(()->invalid("Selected warehouse is unavailable."));
        if(entities!=null) { entities.unwrap(org.hibernate.Session.class).setReadOnly(warehouse,false);entities.refresh(warehouse,LockModeType.PESSIMISTIC_WRITE); }
        if(warehouse.getLatitude()==null||warehouse.getLongitude()==null||warehouse.getLatitude().abs().compareTo(java.math.BigDecimal.valueOf(90))>0||warehouse.getLongitude().abs().compareTo(java.math.BigDecimal.valueOf(180))>0) throw conflict("Selected warehouse needs valid coordinates.");
        return warehouse;
    }
    private Integer legacyWarehouse(String name) {
        if(name==null||name.isBlank()||name.length()>255) throw invalid("Select an existing warehouse.");
        var matches=warehouses.findTop2ByName(name.strip());
        if(matches.isEmpty()) throw invalid("Selected warehouse is unavailable.");
        if(matches.size()>1) throw conflict("Warehouse name is ambiguous. Use warehouse ID selection.");
        return matches.getFirst().getWarehouseId();
    }
    @Transactional(isolation=Isolation.READ_COMMITTED)
    public boolean delete(int id,String etag) { validId(id);requireEtag(etag);return locked(id).map(operator->{match(operator,etag);remove(operator);return true;}).orElse(false); }
    @Transactional(isolation=Isolation.READ_COMMITTED)
    public Optional<OperatorResponseDTO> deleteDriver(int id) { return locked(id).map(operator->{var response=OperatorMapper.toResponseDTO(operator);remove(operator);return response;}); }
    private void remove(Operator operator) {
        int id=operator.getOperatorId();
        if(operators.hasAccounts(id)||operators.hasRoutes(id)||operators.hasDeliveries(id)) throw conflict("Operator has account or delivery history and cannot be deleted.");
        operators.delete(operator);operators.flush();
    }
    private Optional<Operator> locked(int id) {
        return operators.lockById(id).map(operator->{if(entities!=null) { entities.unwrap(org.hibernate.Session.class).setReadOnly(operator,false);entities.refresh(operator,LockModeType.PESSIMISTIC_WRITE); }return operator;});
    }
    private static void validId(int id) { if(id<1) throw invalid("Invalid operator ID."); }
    private static void requireEtag(String etag) {
        if(etag==null||etag.isBlank()) throw new ResponseStatusException(HttpStatus.PRECONDITION_REQUIRED,"Read the operator and provide its ETag in If-Match.");
        if(!etag.matches("\"[a-f0-9]{64}\"")) throw invalid("Provide one strong operator ETag in If-Match.");
    }
    private static void match(Operator operator,String etag) { if(!OperatorState.from(operator).etag().equals(etag)) throw new ResponseStatusException(HttpStatus.PRECONDITION_FAILED,"Operator changed. Reload before retrying."); }
    private static ResponseStatusException invalid(String message) { return new ResponseStatusException(HttpStatus.BAD_REQUEST,message); }
    private static ResponseStatusException conflict(String message) { return new ResponseStatusException(HttpStatus.CONFLICT,message); }
}
